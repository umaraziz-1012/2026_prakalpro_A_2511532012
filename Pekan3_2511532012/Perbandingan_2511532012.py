angka1 = int(input("input angka-1 : "))
angka2 = int(input("input angka-2 : "))

#lebih besar dari
hasil_2012 = angka1 > angka2
print("\nOperator Lebih Besar")
print("angka1 > angka2 = ", hasil_2012)

#lebih kecil dari
hasil_2012 = angka1 < angka2
print("\nOperator Lebih Kecil") 
print("angka1 < angka2 = ", hasil_2012)

#lebih besar dari atau sama dengan
hasil_2012 = angka1 >= angka2
print("\nOperator Lebih Besar atau Sama Dengan")
print("angka1 >= angka2 = ", hasil_2012)

#lebih kecil dari atau sama dengan
hasil_2012 = angka1 <= angka2   
print("\nOperator Lebih Kecil atau Sama Dengan")
print("angka1 <= angka2 = ", hasil_2012)

#sama dengan
hasil_2012 = angka1 == angka2
print("\nOperator Sama Dengan")
print("angka1 == angka2 = ", hasil_2012)

#tidak sama dengan
hasil_2012 = angka1 != angka2
print("\nOperator Tidak Sama Dengan")
print("angka1 != angka2 = ", hasil_2012)

#tambahan perbandingan berantai di python
hasil_2012 = 0 < angka1 < 100
print("\nOperator Perbandingan Berantai")
